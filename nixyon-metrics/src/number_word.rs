/// Слово-число русского языка после нормализации (нижний регистр, «ё» как «е»).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NumberWord {
    /// Количественное до тысячи: значение и разряд (1: единицы и 10-19, 2: десятки,
    /// 3: сотни).
    Cardinal(u64, u8),
    /// Тысяча, миллион, миллиард.
    Multiplier(u64),
    /// Порядковое: значение и разряд, как у количественного; 4 у «тысячного» и выше.
    /// Порядковое слово заканчивает число.
    Ordinal(u64, u8),
}

