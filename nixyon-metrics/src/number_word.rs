// Окончания порядковых во всех родах, числах и падежах; «ь» нужен для «третий».
const ORDINAL_ENDINGS: &[&str] = &[
    "ый", "ой", "ий", "ая", "ое", "ые", "ого", "ому", "ым", "ом", "ых", "ыми", "ую", "ья", "ье",
    "ьи", "ьего", "ьей", "ьему", "ьим", "ьем", "ьих", "ьими", "ью",
];

static WORDS: LazyLock<HashMap<String, NumberWord>> = LazyLock::new(|| {
    let mut words = HashMap::new();
    // Порядковые кладутся первыми: если форма совпала с количественной («пятью»),
    // побеждает количественная.
    for &(value, rank, stem) in ORDINAL_STEMS {
        for ending in ORDINAL_ENDINGS {
            words.insert(format!("{stem}{ending}"), NumberWord::Ordinal(value, rank));
        }
    }
    for &(value, rank, forms) in CARDINALS {
        for form in forms {
            words.insert((*form).to_owned(), NumberWord::Cardinal(value, rank));
        }
    }
    for &(value, stem, endings) in MULTIPLIERS {
        for ending in endings {
            words.insert(format!("{stem}{ending}"), NumberWord::Multiplier(value));
        }
    }
    for &(value, short) in SHORT_MULTIPLIERS {
        words.insert(short.to_owned(), NumberWord::Multiplier(value));
    }
    for &(value, rank, word) in COLLOQUIAL_CARDINALS {
        words.insert(word.to_owned(), NumberWord::Cardinal(value, rank));
    }
    for word in COLLOQUIAL_THOUSANDS {
        words.insert((*word).to_owned(), NumberWord::Multiplier(1_000));
    }
    words
});

/// Слово-число или None. Слово уже нормализовано (`normalize_words`).
pub fn number_word(word: &str) -> Option<NumberWord> {
    WORDS.get(word).copied()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cases_of_cardinals_ordinals_and_multipliers_are_known() {
        assert_eq!(number_word("двадцати"), Some(NumberWord::Cardinal(20, 2)));
        assert_eq!(
            number_word("тремястами"),
            Some(NumberWord::Cardinal(300, 3))
        );
        assert_eq!(
            number_word("миллиардов"),
            Some(NumberWord::Multiplier(1_000_000_000))
        );
        assert_eq!(number_word("тысячу"), Some(NumberWord::Multiplier(1_000)));
        assert_eq!(number_word("млн"), Some(NumberWord::Multiplier(1_000_000)));
        assert_eq!(number_word("втором"), Some(NumberWord::Ordinal(2, 1)));
        assert_eq!(number_word("третьей"), Some(NumberWord::Ordinal(3, 1)));
        assert_eq!(number_word("сотый"), Some(NumberWord::Ordinal(100, 3)));
    }

    #[test]
    fn a_cardinal_form_wins_over_the_same_ordinal_form_and_plain_words_are_not_numbers() {
        assert_eq!(number_word("пятью"), Some(NumberWord::Cardinal(5, 1)));
        assert_eq!(number_word("десятью"), Some(NumberWord::Cardinal(10, 1)));
        assert_eq!(number_word("пальто"), None);
        assert_eq!(number_word("сот"), None);
    }
}
