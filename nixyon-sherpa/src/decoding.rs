/// Прибавка за каждый токен горячего слова. По замеру на 6 записях 1,5 даёт наименьший
/// WER; от 3,0 модель начинает вставлять слова из списка там, где их не говорили.
/// То же значение в SpeechModels.kt.
pub const HOTWORD_SCORE: f32 = 1.5;

/// Число лучей поиска. По замеру на 6 записях WER снижается до 8 лучей и дальше
/// не меняется (1: 12,2 %, 4: 11,8 %, 8 и 12: 11,5 %). То же значение в SpeechModels.kt.
pub const BEAM_PATHS: i32 = 8;

/// Как распознаватель ищет текст. Модель в памяти одна, способ задаётся при загрузке.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Decoding {
    /// Жадный поиск: быстрее, горячих слов нет.
    Greedy,
    /// Поиск по лучам (modified_beam_search) с горячими словами; `score`: прибавка
    /// к оценке за каждый токен горячего слова, `paths`: число лучей. Нужен словарь BPE
    /// в наборе моделей.
    HotwordBeam { score: f32, paths: i32 },
}

impl Default for Decoding {
    /// Как в приложении: поиск по лучам всегда, чтобы горячие слова работали без второй
    /// копии модели; без слов текст тот же, что у жадного поиска, но дольше.
    fn default() -> Self {
        Decoding::HotwordBeam {
            score: HOTWORD_SCORE,
            paths: BEAM_PATHS,
        }
    }
}
