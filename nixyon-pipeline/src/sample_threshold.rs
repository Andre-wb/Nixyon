/// Значение по умолчанию для `PipelineOptions::sample_threshold`. Середина диапазона,
/// где по замеру нет ни ложных имён, ни пропусков (0,4..0,7): ниже 0,4 человек без
/// образца получает имя отсутствующего, от 0,8 свои голоса остаются без имени. Для
/// центров прошлых встреч тот же порог: по замеру с ними ошибок и пропусков нет на
/// 0,3..0,7, а на 0,8 появляются пропуски.
pub const SAMPLE_THRESHOLD: f64 = 0.55;
