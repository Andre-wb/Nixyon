/// Как сравнить центр спикера с человеком, у которого несколько эмбеддингов голоса
/// (образец и центры прошлых встреч).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum VoiceMatch {
    /// Наибольший косинус по всем эмбеддингам человека.
    Max,
    /// Косинус со средним единичных эмбеддингов человека.
    Mean,
}
