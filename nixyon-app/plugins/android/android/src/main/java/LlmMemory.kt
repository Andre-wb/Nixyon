package dev.demo.nixyon.speech

// Хватит ли памяти на языковую модель. Веса llama.cpp отображает прямо из файла (mmap, так
// открывается и модель из APK, и модель из папки): это страницы файла, система может вытеснить
// их и прочитать заново, поэтому файл целиком в свободной памяти не нужен. Прежняя проверка
// требовала размер файла и ещё 768 МБ, около 3,3 ГБ для Qwen3.5-4B, и на телефоне с 8 ГБ не
// проходила, даже когда все приложения закрыты. Теперь нужна только память, которую llama.cpp
// выделяет сам: кэш KV на контекст 4096 токенов и рабочие буферы (те же 768 МБ), и ещё 256 МБ,
// чтобы самые нужные веса оставались в памяти. Если свободно меньше размера файла, ответ идёт
// медленнее: часть весов читается с диска заново.
object LlmMemory {
    const val WORKING_BYTES = 1024L shl 20

    fun isEnough(availableBytes: Long, lowMemory: Boolean): Boolean =
        !lowMemory && availableBytes >= WORKING_BYTES
}
