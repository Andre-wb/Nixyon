package dev.demo.nixyon.speech

// Как грузить языковую модель при такой свободной памяти.
//
// На процессорах с dotprod или i8mm (почти все телефоны с 2018 года) llama.cpp при загрузке
// перекладывает веса Q4_K, Q5_K и Q6_K в свой порядок под эти инструкции (repack, буфер
// CPU_REPACK). Это копия таких весов в обычной памяти процесса, рядом с отображённым файлом:
// модель считает быстрее, но памяти нужно на сам файл и ещё рабочие буферы. Без перекладки
// веса остаются страницами файла (mmap): система вытесняет их и читает заново, поэтому
// достаточно памяти на рабочие буферы, а ответ идёт медленнее, когда файл не помещается.
// Замер на ноутбуке (x86, llama.cpp той же ветки, модель Q4_K_M 523 МБ, контекст 4096): с
// перекладкой своей памяти процесса после загрузки 478 МБ, без неё 5 МБ, веса в обоих
// случаях читаются из файла. Прежняя проверка «свободно 1 ГБ» считала, что веса всегда
// остаются в файле, и пускала быструю загрузку туда, где на копию весов памяти нет.
enum class LlmLoad(val repack: Boolean) {
    FAST(true),
    LOW_MEMORY(false),
}

object LlmMemory {
    // Кэш KV на контекст 4096 токенов и рабочие буферы llama.cpp (около 768 МБ) и 256 МБ,
    // чтобы самые нужные страницы весов оставались в памяти.
    const val WORKING_BYTES = 1024L shl 20

    // Быстро, если помещается копия всей модели (верхняя граница перекладки) и рабочие
    // буферы; из файла, если помещаются только буферы; иначе модель не грузится. lowMemory:
    // система сама сообщает, что память на исходе.
    fun choose(availableBytes: Long, lowMemory: Boolean, modelBytes: Long): LlmLoad? = when {
        lowMemory -> null
        availableBytes - WORKING_BYTES >= modelBytes -> LlmLoad.FAST
        availableBytes >= WORKING_BYTES -> LlmLoad.LOW_MEMORY
        else -> null
    }
}
