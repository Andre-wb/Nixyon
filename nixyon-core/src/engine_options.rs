use crate::{SpeechEdges, WindowSpec};

/// Что движок считает сверх текста и эмбеддинга куска. По умолчанию ничего:
/// эмбеддинги по окнам примерно утраивают работу модели голоса.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct EngineOptions {
    pub windows: Option<WindowSpec>,
    /// Горячие слова и фразы: распознавание охотнее выбирает их. Пусто: без них.
    pub hotwords: Vec<String>,
    pub edges: SpeechEdges,
    /// Наибольшая длина куска речи, секунды. None: как в приложении (20 с).
    pub max_speech_sec: Option<f32>,
    /// Не распознавать куски, где вместо речи звучит музыка или пение.
    pub drop_music: bool,
    /// Соседние куски с короткой паузой распознавать вместе, одним отрезком звука, а слова
    /// раздавать по кускам: фраза, разрезанная паузой, не рвётся на предложения.
    pub asr_groups: bool,
}
