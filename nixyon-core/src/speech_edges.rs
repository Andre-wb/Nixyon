/// Как движок режет запись на куски речи.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum SpeechEdges {
    /// Как в приложении: чувствительный VAD, куски с запасом по краям, короткая запись
    /// без найденной речи идёт целиком. Слова на краях фразы не теряются.
    #[default]
    Padded,
    /// Строгий VAD и куски вплотную к речи. Деление на спикеров по кускам VAD (без
    /// нейросегментации) держится на паузах между репликами, а чувствительный VAD
    /// склеивает реплики разных людей.
    Tight,
}
