use crate::EngineError;

/// Нейросегментация одного блока звука: где в нём говорит каждый говорящий. Номера
/// говорящих не возвращаются: их назначает кластеризация по всей записи.
pub trait BlockSegmenter: Send + Sync {
    /// `block_16k`: моно 16 кГц. Отрезки (начало, конец) в секундах от начала блока,
    /// у разных говорящих они могут пересекаться.
    fn speaker_spans(&self, block_16k: &[f32]) -> Result<Vec<(f64, f64)>, EngineError>;
}
