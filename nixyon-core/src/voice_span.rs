/// Отрезок речи одного говорящего от нейросегментации, обрезанный по куску VAD,
/// с эмбеддингом голоса на этом отрезке. Отрезки разных говорящих могут
/// пересекаться по времени: там говорят одновременно.
#[derive(Debug, Clone, PartialEq)]
pub struct VoiceSpan {
    /// Секунды от начала записи.
    pub start: f64,
    pub end: f64,
    pub embedding: Vec<f32>,
}
