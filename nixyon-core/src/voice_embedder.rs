use crate::EngineError;

/// Модель голоса: эмбеддинг куска речи. Разные модели взаимозаменяемы, пока весь
/// конвейер одной записи (куски, окна, отрезки, образцы) считает одной и той же.
pub trait VoiceEmbedder: Send + Sync {
    /// `samples_16k`: моно 16 кГц. Пустой результат: кусок слишком короткий для модели.
    fn embed(&self, samples_16k: &[f32]) -> Result<Vec<f32>, EngineError>;

    /// Длина эмбеддинга.
    fn dim(&self) -> usize;
}
